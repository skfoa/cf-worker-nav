/**
 * scripts/gen-asset-manifest.mjs
 * 根据 public/output.css 与 public/client.min.js 生成短哈希版本常量
 */
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'

function shortHash(filePath) {
  if (!fs.existsSync(filePath)) return 'dev'
  const buf = fs.readFileSync(filePath)
  return crypto.createHash('sha256').update(buf).digest('hex').slice(0, 8)
}

const cssHash = shortHash(path.resolve('public/output.css'))
const jsHash = shortHash(path.resolve('public/client.min.js'))

const outDir = path.resolve('src/generated')
fs.mkdirSync(outDir, { recursive: true })
const outFile = path.join(outDir, 'assets.ts')
const content =
  '// Auto-generated by scripts/gen-asset-manifest.mjs — do not edit manually\n' +
  'export const ASSET_VERSIONS = {\n' +
  `  css: '${cssHash}',\n` +
  `  js: '${jsHash}',\n` +
  '} as const\n'

fs.writeFileSync(outFile, content, 'utf8')
console.log(`Generated ${path.relative(process.cwd(), outFile)}: css=${cssHash}, js=${jsHash}`)

